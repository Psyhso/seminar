# =============================================================================
# WSD через word2vec
# =============================================================================
#
# Идея: представляем каждое значение слова как набор слов-ассоциаций.
# Усредняем их векторы и сравниваем с вектором контекста.
#
# Главное ограничение: инвентарь значений написан вручную.
# Для каждого нового слова нужно заново думать и заполнять SENSE_INVENTORY.
#
# Зависимости:
#   pip install gensim scikit-learn numpy
#
# Модель:
#   ruscorpora_upos_cbow_300_20_2019.bin.gz — скачать с rusvectores.org
# =============================================================================

import numpy as np
from gensim.models import KeyedVectors
from sklearn.metrics.pairwise import cosine_similarity


# =============================================================================
# 1. ЗАГРУЗКА МОДЕЛИ
# =============================================================================

print("Загружаю модель...")
model = KeyedVectors.load_word2vec_format(
    './dataset/model.bin',
    binary=True
)
print("Готово!\n")


# =============================================================================
# 2. ИНВЕНТАРЬ ЗНАЧЕНИЙ — ЗАПОЛНЯЕТСЯ ВРУЧНУЮ
# =============================================================================
# Для каждого слова нужно вручную придумать слова-ассоциации для каждого
# значения. Это и есть главная проблема подхода — человек уже знает ответ
# до запуска алгоритма.

SENSE_INVENTORY = {
    'замок': {
        'крепость':   ['башня', 'стена', 'рыцарь', 'средневековый', 'крепость'],
        'устройство': ['ключ', 'дверь', 'открыть', 'закрыть', 'скважина'],
    },
    'ключ': {
        'инструмент': ['замок', 'дверь', 'открыть', 'скважина', 'отмычка'],
        'родник':     ['вода', 'скала', 'течь', 'ручей', 'бить'],
        'решение':    ['задача', 'ответ', 'разгадка', 'метод'],
    },
    'лук': {
        'оружие':   ['стрела', 'тетива', 'лучник', 'колчан', 'стрелять'],
        'растение': ['овощ', 'огород', 'жарить', 'суп', 'горький'],
        'танец':    ['балет', 'поклон', 'сцена', 'аплодисменты'],
    },
    'дорого': {
        'цена':     ['цена', 'деньги', 'купить', 'магазин', 'стоить'],
        'ценность': ['память', 'сердце', 'чувство', 'близкий', 'дорожить'],
    },
    'ручка': {
        'письмо':   ['писать', 'бумага', 'чернила', 'тетрадь', 'перо'],
        'дверь':    ['дверь', 'открыть', 'держать', 'металл', 'повернуть'],
        'рука':     ['ребёнок', 'маленький', 'держать', 'ладонь'],
    },
}

# =============================================================================
# 3. ТЕСТОВЫЕ ПРИМЕРЫ
# =============================================================================

test_cases = [
    ('замок', ['башня', 'средневековый', 'стена', 'рыцарь'],   'крепость'),
    ('замок', ['ключ', 'дверь', 'открыть', 'запирать'],        'устройство'),
    ('замок', ['каменный', 'старый', 'красивый'],              'крепость'),
    ('замок', ['губы', 'молчать', 'держать'],                  'устройство'),
    ('замок', ['бойница', 'донжон', 'ров'],                    'крепость'),
    ('ключ',  ['вставить', 'замок', 'дверь'],                  'инструмент'),
    ('ключ',  ['скала', 'бить', 'холодный'],                   'родник'),
    ('ключ',  ['найти', 'решение', 'задача'],                  'решение'),
    ('ключ',  ['металлический', 'найти', 'карман'],            'инструмент'),
]


# =============================================================================
# 4. АЛГОРИТМ
# =============================================================================

def word_to_vec(word):
    for pos in ['NOUN', 'VERB', 'ADJ', 'ADV']:
        if f"{word}_{pos}" in model:
            return model[f"{word}_{pos}"]
    return None

def get_mean_vector(words):
    vecs = [word_to_vec(w) for w in words if word_to_vec(w) is not None]
    return np.mean(vecs, axis=0) if vecs else None

def wsd_word2vec(context_words, word):
    context_vec = get_mean_vector(context_words)
    if context_vec is None:
        return None, {}

    scores = {}
    for sense_name, sense_words in SENSE_INVENTORY.get(word, {}).items():
        sense_vec = get_mean_vector(sense_words)
        if sense_vec is not None:
            scores[sense_name] = float(cosine_similarity(
                context_vec.reshape(1, -1),
                sense_vec.reshape(1, -1)
            )[0][0])

    best = max(scores, key=scores.get) if scores else None
    return best, scores


# =============================================================================
# 5. ЗАПУСК
# =============================================================================

W = 72
print("=" * W)
print(f"{'СЛОВО':<8} {'КОНТЕКСТ':<36} {'ВЕРНО':<12} {'ПРЕДСКАЗАНО':<12} {'OK':^4}")
print("=" * W)

correct = 0
for word, context, true_sense in test_cases:
    pred, scores = wsd_word2vec(context, word)
    ok = '✅' if pred == true_sense else '❌'
    correct += (ok == '✅')
    scores_str = ' '.join(f"{k}:{v:.2f}" for k, v in scores.items())
    print(f"{word:<8} {str(context)[:34]:<36} {true_sense:<12} {str(pred):<12} {ok:^4}")
    print(f"         Scores: {scores_str}")
    print()

print("=" * W)
print(f"ACCURACY: {correct}/{len(test_cases)}")
print("=" * W)
print()
print("Вывод: word2vec справляется хорошо — но только потому что инвентарь")
print("значений написан вручную. Алгоритм не знает языка — он измеряет")
print("расстояние до твоих же подсказок.")